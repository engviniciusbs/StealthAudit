<?php
/**
 * Theme-independent panel route with query-var fallback and a leased rewrite flush.
 *
 * @package StealthAudit
 */

declare(strict_types=1);
namespace StealthAudit\Http;

use StealthAudit\Storage\StateRepository;

/** Serves the page before the main query and theme; never flushes on every request. */
final class Router {
	public const LEASE_SECONDS = 300;

	/**
	 * Construct.
	 *
	 * @param Urls                       $urls Central URL generation.
	 * @param Panel                      $panel Page controller.
	 * @param \Closure():StateRepository $state Ready state store or throws.
	 * @param \Closure():int             $clock UTC clock.
	 */
	public function __construct(
		private readonly Urls $urls,
		private readonly Panel $panel,
		private readonly \Closure $state,
		private readonly \Closure $clock,
	) {}

	/** Register hooks at the WordPress lifecycle boundaries. */
	public function register(): void {
		add_action( 'init', array( $this, 'add_rules' ) );
		add_filter( 'query_vars', array( $this, 'query_vars' ) );
		add_action( 'wp_loaded', array( $this, 'loaded' ) );
		add_action( 'parse_request', array( $this, 'serve' ), 0 );
	}

	/** Top priority so an existing page with the same slug cannot shadow the panel. */
	public function add_rules(): void {
		add_rewrite_rule( $this->urls->rule(), 'index.php?' . Urls::QUERY_VAR . '=panel', 'top' );
	}

	/**
	 * Public query var for plain permalinks and servers without friendly paths.
	 *
	 * @param mixed $vars Registered public query vars.
	 * @return mixed Vars including ours.
	 */
	public function query_vars( mixed $vars ): mixed {
		if ( is_array( $vars ) ) {
			$vars[] = Urls::QUERY_VAR;
		}
		return $vars;
	}

	/**
	 * Whether the parsed request targets the panel.
	 *
	 * @param \WP $wp Parsed request.
	 */
	public function matches( \WP $wp ): bool {
		return 'panel' === ( $wp->query_vars[ Urls::QUERY_VAR ] ?? null );
	}

	/**
	 * Emit the panel response and stop before the main query/theme.
	 *
	 * @param mixed $wp Parsed request.
	 */
	public function serve( mixed $wp ): void {
		if ( ! $wp instanceof \WP || ! $this->matches( $wp ) ) {
			return;
		}
		$method   = isset( $_SERVER['REQUEST_METHOD'] ) && is_string( $_SERVER['REQUEST_METHOD'] ) ? strtoupper( $_SERVER['REQUEST_METHOD'] ) : ''; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput -- Compared against a closed method list only.
		$response = $this->panel->respond( $method, wp_unslash( $_GET ) ); // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Read-only view filters, strictly validated by Filters.
		if ( ! defined( 'DONOTCACHEPAGE' ) ) {
			define( 'DONOTCACHEPAGE', true ); // phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals -- Page-cache plugin convention.
		}
		if ( ! headers_sent() ) {
			nocache_headers();
			status_header( $response->status );
			foreach ( $response->headers as $name => $value ) {
				header( $name . ': ' . $value );
			}
		}
		if ( 'HEAD' !== $method ) {
			echo $response->body; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Body is built from escaped template output and fixed literals.
		}
		exit;
	}

	/** Lifecycle hook wrapper; actions return nothing. */
	public function loaded(): void {
		$this->maybe_flush();
	}

	/**
	 * Flush once when the stored rules lack our rule, at most once per lease window.
	 *
	 * Plain permalinks need no rules; a missing option is regenerated by WordPress itself.
	 *
	 * @return bool Whether this request flushed.
	 */
	public function maybe_flush(): bool {
		if ( '' === (string) get_option( 'permalink_structure' ) ) {
			return false;
		}
		$rules = get_option( 'rewrite_rules' );
		if ( ! is_array( $rules ) || isset( $rules[ $this->urls->rule() ] ) ) {
			return false;
		}
		try {
			$state = ( $this->state )();
			$now   = ( $this->clock )();
			$key   = 'lease:' . hash( 'sha256', 'rewrite:' . $this->urls->rule() );
			$lease = array( 'owner' => bin2hex( random_bytes( 16 ) ) );
			// The lease is never released early: a flush that does not persist cannot repeat
			// before it expires. Contention or storage failure skip the flush (fallback still works).
			// A live lease returns before create(), which would reserve state capacity.
			if ( null !== $state->get( $key, $now ) || ( ! $state->replace_expired( $key, $lease, $now + self::LEASE_SECONDS, $now ) && ! $state->create( $key, $lease, $now + self::LEASE_SECONDS ) ) ) {
				return false;
			}
		} catch ( \Throwable $failure ) {
			return false;
		}
		flush_rewrite_rules( false );
		return true;
	}
}
