// PHP-Scoper configuration used only by tools/package.php (never shipped). The PHP-Scoper release
// is pinned once, as STEALTHAUDIT_SCOPER_VERSION in tools/package-lib.php.
//
// Scope ONLY the production vendor tree of a clean temporary build: every third-party symbol
// moves under StealthAuditVendor\. The product's own code (src/, templates/, loader, bin/) is not
// given to PHP-Scoper: it would also prefix WordPress classes, functions and constants
// (\WP_Error, \wpdb, REST_REQUEST, DOING_AUTOSAVE, Core_Upgrader...) and our own STEALTHAUDIT_*
// constants. tools/package.php rewrites the few vendor imports in src/ with a token-exact pass
// instead, and tools/verify-package.php proves the result.
//
// STEALTHAUDIT_BUILD_DIR is the temporary build root holding vendor/ (set by tools/package.php).
use Isolated\Symfony\Component\Finder\Finder;

$stealthaudit_build = getenv( 'STEALTHAUDIT_BUILD_DIR' );
if ( ! is_string( $stealthaudit_build ) || '' === $stealthaudit_build || ! is_dir( $stealthaudit_build . '/vendor' ) ) {
	throw new RuntimeException( 'STEALTHAUDIT_BUILD_DIR must point at the temporary build directory.' );
}

return array(
	'prefix'                  => 'StealthAuditVendor',
	'output-dir'              => null,
	'finders'                 => array(
		// Composer's own runtime files (vendor/autoload.php, vendor/composer/*.php|json) are
		// regenerated by "composer dump-autoload" afterwards; vendor/composer/ca-bundle/ is a package.
		Finder::create()->files()->ignoreVCS( true )->ignoreDotFiles( false )->in( $stealthaudit_build . '/vendor' )->notPath( '#^composer/[^/]+$#' )->notPath( '#^bin/#' )->depth( '> 0' ),
		// Scoping installed.json rewrites the PSR-4 roots that dump-autoload reads.
		Finder::create()->files()->in( $stealthaudit_build . '/vendor/composer' )->name( 'installed.json' ),
	),
	'exclude-files'           => array(),
	'exclude-namespaces'      => array(),
	'exclude-classes'         => array(),
	'exclude-functions'       => array(),
	'exclude-constants'       => array(),
	// Nothing is exposed under its original global name: no scoper-autoload.php aliases.
	'expose-global-constants' => false,
	'expose-global-classes'   => false,
	'expose-global-functions' => false,
	'expose-namespaces'       => array(),
	'expose-classes'          => array(),
	'expose-functions'        => array(),
	'expose-constants'        => array(),
	'patchers'                => array(
		/*
		 * symfony/deprecation-contracts declares the global function trigger_deprecation(); scoped,
		 * it becomes StealthAuditVendor\trigger_deprecation(). PHP-Scoper leaves UNQUALIFIED calls
		 * in namespaced code untouched, and PHP resolves those to the namespace and then to the
		 * GLOBAL function: another plugin's copy, or a fatal "undefined function". Qualify them.
		 */
		static function ( string $file_path, string $prefix, string $contents ): string {
			if ( ! str_ends_with( $file_path, '.php' ) || ! str_contains( $contents, 'trigger_deprecation' ) ) {
				return $contents;
			}
			return (string) preg_replace( '/(?<![\\\\\w$>:])(?<!function )trigger_deprecation\s*\(/', '\\' . $prefix . '\\trigger_deprecation(', $contents );
		},
		/*
		 * PHP-Scoper never prefixes symbols it believes are PHP-internal (its list comes from the
		 * JetBrains stubs, extensions included). The optional maxminddb C extension declares
		 * MaxMind\Db\Reader, so "use MaxMind\Db\Reader" in geoip2 stayed UNPREFIXED: GeoIP then
		 * failed ("class not found") or would silently use the extension / another plugin's copy.
		 * Prefix every remaining reference to a namespace this vendor tree really ships, with the
		 * same token pass used for the product code; anything it cannot rewrite stops the build.
		 */
		static function ( string $file_path, string $prefix, string $contents ): string {
			if ( ! str_ends_with( $file_path, '.php' ) ) {
				return $contents;
			}
			require_once __DIR__ . '/package-lib.php';
			$roots  = json_decode( (string) getenv( 'STEALTHAUDIT_SCOPER_ROOTS' ), true, 4, JSON_THROW_ON_ERROR );
			$result = stealthaudit_package_prefix_source( $contents, $roots, false, true );
			if ( array() !== $result['problems'] ) {
				throw new RuntimeException( $file_path . ': ' . implode( '; ', $result['problems'] ) );
			}
			return $result['code'];
		},
	),
);
